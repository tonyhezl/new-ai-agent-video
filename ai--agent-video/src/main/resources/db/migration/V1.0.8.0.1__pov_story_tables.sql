CREATE TABLE IF NOT EXISTS `afv_pov_story` (
  `id` BIGINT NOT NULL AUTO_INCREMENT COMMENT '主键ID',
  `user_id` BIGINT NOT NULL COMMENT '所属用户ID',
  `project_id` BIGINT NULL COMMENT '关联项目ID（可选）',
  `title` VARCHAR(255) NOT NULL COMMENT '故事标题',
  `hook_text` TEXT NULL COMMENT '黄金钩子文案',
  `topic_genre` VARCHAR(64) NOT NULL DEFAULT 'URBAN_MYSTERY' COMMENT '题材类型: URBAN_MYSTERY/DEEP_EXPLORATION/SECRET_REVEAL/TECH_PARANOIA',
  `full_script` MEDIUMTEXT NOT NULL COMMENT '完整第一人称独白脚本',
  `total_duration_estimate` INT NOT NULL DEFAULT 50 COMMENT '预估时长(秒)',
  `voice_id` VARCHAR(64) DEFAULT 'zh-CN-YunyangNeural' COMMENT '配音音色',
  `bgm_style` VARCHAR(64) DEFAULT 'SUSPENSE_HEARTBEAT' COMMENT '背景氛围音效类型',
  `status` VARCHAR(32) NOT NULL DEFAULT 'DRAFT' COMMENT '状态: DRAFT/GENERATING/COMPLETED/FAILED',
  `final_video_url` VARCHAR(512) NULL COMMENT '最终合成视频URL',
  `error_message` VARCHAR(1024) NULL COMMENT '错误信息',
  `create_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `update_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  `deleted` TINYINT(1) NOT NULL DEFAULT 0 COMMENT '逻辑删除',
  PRIMARY KEY (`id`),
  KEY `idx_user_id` (`user_id`),
  KEY `idx_project_id` (`project_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='第一人称猎奇故事主表';

CREATE TABLE IF NOT EXISTS `afv_pov_shot` (
  `id` BIGINT NOT NULL AUTO_INCREMENT COMMENT '主键ID',
  `story_id` BIGINT NOT NULL COMMENT '所属故事ID',
  `shot_order` INT NOT NULL COMMENT '镜头序号(1..N)',
  `narrative_stage` VARCHAR(32) NOT NULL DEFAULT 'EXPLORE' COMMENT '叙事阶段: HOOK/EXPLORE/TWIST/CLIMAX',
  `voice_text` TEXT NOT NULL COMMENT '第一人称独白台词',
  `visual_prompt` TEXT NOT NULL COMMENT 'POV视觉生图提示词',
  `negative_prompt` TEXT NULL COMMENT '负向提示词',
  `camera_view` VARCHAR(64) DEFAULT 'POV_HANDHELD' COMMENT '机位视角',
  `sfx_cue` VARCHAR(64) NULL COMMENT '音效触发点',
  `duration_sec` DECIMAL(5,2) NOT NULL DEFAULT 4.00 COMMENT '镜头时长',
  `image_url` VARCHAR(512) NULL COMMENT '生图产物URL',
  `video_url` VARCHAR(512) NULL COMMENT '生视频产物URL',
  `audio_url` VARCHAR(512) NULL COMMENT '独白音频URL',
  `status` VARCHAR(32) NOT NULL DEFAULT 'PENDING' COMMENT '状态: PENDING/GENERATING/COMPLETED/FAILED',
  `error_message` VARCHAR(1024) NULL COMMENT '错误信息',
  `create_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `update_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  `deleted` TINYINT(1) NOT NULL DEFAULT 0 COMMENT '逻辑删除',
  PRIMARY KEY (`id`),
  KEY `idx_story_order` (`story_id`, `shot_order`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='第一人称POV分镜表';
